export CARGO=/usr/local/bin/cargo
export RUSTC=/usr/local/bin/rustc

TOTAL=${#RUST_LIBS[@]}
CURRENT=0

for entry in "${RUST_LIBS[@]}"; do
  IFS=':' read -r \
    rust_lib \
    repackage_name \
    patch_name \
    <<< "$entry"

  # Print progress bar
  BAR_WIDTH=40
  ROWS=$(tput lines)
  printf "\033[1;$(($ROWS - 1))r"
  printf "\n%.0s" $(seq 1 $ROWS)
  tput civis
  printf "\033[s"
  printf "\033[${ROWS};1H"
  PERCENT=$(( CURRENT * 100 / TOTAL))
  FILLED=$(( CURRENT * BAR_WIDTH / TOTAL))
  EMPTY=$(( BAR_WIDTH - FILLED ))
  BAR=$(printf "%${FILLED}s" | tr ' ' '#')
  SPACE=$(printf "%${EMPTY}s" | tr ' ' '-')
  printf "\033[K\e[30;46m[%s%s] %d%% (%d/%d) building ${repackage_name}...\e[0m" "$BAR" "$SPACE" "$PERCENT" "$CURRENT" "$TOTAL"
  printf "\033[u"

  echo "####################"
  echo "Build start... [${CURRENT}/${TOTAL}]"
  echo "Building rust package ${repackage_name}..."
  echo "CARGO: $($CARGO --version)"
  echo "RUSTC: $($RUSTC --version)"
  echo "DEBCARGO: $(debcargo --version)"
  rm -rf ./build/*
  # Prepare patch for ./repackage.sh script
  cp -r "./src/${rust_lib}/" "/tmp/tmp_${rust_lib}"
  if [[ $patch_name == "none" ]]; then
    rm -rf "./src/${rust_lib}/debian/patches/"
    rm -rf "./src/${rust_lib}/debian/patches_*/"
    ./repackage.sh ${repackage_name}
  elif [[ $patch_name == "patches" ]]; then
    rm -rf "./src/${rust_lib}/debian/patches_*/"
    ./repackage.sh ${repackage_name}
  else
    rm -rf "./src/${rust_lib}/debian/patches/"
    mv "./src/${rust_lib}/debian/${patch_name}/" "./src/${rust_lib}/debian/patches"
    rm -rf "./src/${rust_lib}/debian/patches_*/"
    ./repackage.sh ${repackage_name}
  fi
  rm -rf "./src/${rust_lib}/"
  mv "/tmp/tmp_${rust_lib}" "./src/${rust_lib}"
  # Build librust package
  (
    cd ./build/${rust_lib}/ && \
    yes |mk-build-deps --install --remove; \
    dpkg-buildpackage -b -us -uc
  )
  mkdir -p /tmp/${PKGNAME}-temp
  mkdir -p /tmp/${PKGNAME}
  for deb_pkg in $(find $(pwd)/build/ -name "*.deb"); do
    cp ${deb_pkg} "/tmp/${PKGNAME}-temp/"
    cp ${deb_pkg} "/tmp/${PKGNAME}/"
  done
  apt install --reinstall -y --allow-downgrades --reinstall /tmp/${PKGNAME}-temp/*.deb || exit 1 &&
  rm -rf /tmp/${PKGNAME}-temp
  CURRENT=$((CURRENT + 1))
  echo "Build finished for rust library ${repackage_name}... [${CURRENT}/${TOTAL}]"
  # Print progress bar
  BAR_WIDTH=40
  ROWS=$(tput lines)
  printf "\033[1;$(($ROWS - 1))r"
  printf "\n%.0s" $(seq 1 $ROWS)
  tput civis
  printf "\033[s"
  printf "\033[${ROWS};1H"
  PERCENT=$(( CURRENT * 100 / TOTAL))
  FILLED=$(( CURRENT * BAR_WIDTH / TOTAL))
  EMPTY=$(( BAR_WIDTH - FILLED ))
  BAR=$(printf "%${FILLED}s" | tr ' ' '#')
  SPACE=$(printf "%${EMPTY}s" | tr ' ' '-')
  printf "\033[K\e[30;46m[%s%s] %d%% (%d/%d) building ${repackage_name}...\e[0m" "$BAR" "$SPACE" "$PERCENT" "$CURRENT" "$TOTAL"
  printf "\033[u"
done

